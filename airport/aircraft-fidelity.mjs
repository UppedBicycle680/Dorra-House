function sample(profile,t){
  let i=0;while(i<profile.length-2&&profile[i+1][0]<t)i++;
  const a=profile[i],b=profile[i+1],u=Math.max(0,Math.min(1,(t-a[0])/(b[0]-a[0])));
  // Monotone cubic interpolation avoids overshoot at the constant cabin barrel.
  return a.map((v,j)=>{
    if(!j)return t;
    const prev=profile[Math.max(0,i-1)],next=profile[Math.min(profile.length-1,i+2)],d=(b[j]-v)/(b[0]-a[0]);
    const slope=(p,q)=>((p[j]-q[j])/(p[0]-q[0]||1));
    const limit=s=>d===0||s*d<=0?0:Math.sign(d)*Math.min(Math.abs(s),3*Math.abs(d));
    const ma=limit(slope(b,prev))*(b[0]-a[0]),mb=limit(slope(next,a))*(b[0]-a[0]);
    return (2*u*u*u-3*u*u+1)*v+(u*u*u-2*u*u+u)*ma+(-2*u*u*u+3*u*u)*b[j]+(u*u*u-u*u)*mb;
  });
}

// Keep the lazy accessors outside the builder's closure scope: retaining that
// scope would also retain arrays used by its temporary modelling helpers.
function compactAircraft(m,metadata,packed){
  let detailed;
  const geometry={...metadata,packed};
  const detail=()=>{if(!detailed){detailed=buildFidelityAircraft(m);geometry.packed=null}return detailed};
  Object.defineProperties(geometry,{faces:{get:()=>detail().faces},vertices:{get:()=>detail().vertices},
    releaseInspectionGeometry:{value:()=>{detailed=undefined;geometry.packed=packed}}});
  return geometry;
}

