function triangulate(poly){
  const area=poly.reduce((sum,a,i)=>{const b=poly[(i+1)%poly.length];return sum+a[0]*b[1]-b[0]*a[1]},0),sign=Math.sign(area),ids=poly.map((_,i)=>i),result=[];
  const turn=(a,b,c)=>(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0]);
  while(ids.length>3){
    let found=false;
    for(let k=0;k<ids.length;k++){
      const a=ids[(k+ids.length-1)%ids.length],b=ids[k],c=ids[(k+1)%ids.length];if(sign*turn(poly[a],poly[b],poly[c])<=1e-8)continue;
      if(ids.some(i=>i!==a&&i!==b&&i!==c&&sign*turn(poly[a],poly[b],poly[i])>=0&&sign*turn(poly[b],poly[c],poly[i])>=0&&sign*turn(poly[c],poly[a],poly[i])>=0))continue;
      result.push([a,b,c]);ids.splice(k,1);found=true;break;
    }
    if(!found)throw Error('Invalid aircraft fin contour');
  }
  result.push(ids);return result;
}

