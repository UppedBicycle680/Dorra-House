import {writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {AIRPORTS,AIRCRAFT,RUNWAY_LENGTHS} from '../airport/catalog.mjs';
import {getAirportLayout} from '../airport/layouts.mjs';
import {createFlightPlan,roundedPath} from '../airport/traffic.mjs';
import {AIRCRAFT_DIMENSIONS} from '../airport/aircraft-dimensions.mjs';
import {aircraftFitsBay} from '../airport/brisbane-bays.mjs';
import {BRISBANE_ROUTE_ADJUSTMENTS} from '../airport/brisbane-route-adjustments.mjs';
import {bayRouteSignature} from '../airport/brisbane-traffic.mjs';
import {compileBrisbaneRequirements} from '../airport/operations-route-compiler.mjs';
import {operationsRouteSourceHashes} from './operations-route-inputs.mjs';

const hashes=await operationsRouteSourceHashes();
const version=createHash('sha256').update(JSON.stringify(hashes)).digest('hex').slice(0,16);
const entries={};let checked=0,accepted=0;
for(const meta of AIRPORTS){
  const layout=getAirportLayout(meta.id),lengths=RUNWAY_LENGTHS.filter(n=>n<=meta.maxRunwayLength);
  for(const stand of layout.stands){
    const phaseCache=new Map();
    for(const aircraft of AIRCRAFT){
    if(aircraft.size>meta.maxSize||!aircraftFitsBay(meta.id,stand.plotId,aircraft.id))continue;
    const model={id:aircraft.id,...AIRCRAFT_DIMENSIONS[aircraft.id]};
    const adjustment=BRISBANE_ROUTE_ADJUSTMENTS[`${stand.plotId}:${aircraft.id}`];
    const turn=meta.id==='brisbane'&&adjustment?.signature===bayRouteSignature(stand)&&adjustment.taxiwayVersion===layout.taxiwayVersion?adjustment.turnFactor??.3:.3;
    const stages=layout.fixedReferenceRunway?[meta.maxRunwayLength]:lengths.filter(n=>n>=aircraft.runwayLength);
    for(const length of stages){
      if(length<aircraft.runwayLength)continue;
      checked++;
      const view={...meta,runwayLength:length,gates:[],routeTurnFactor:turn,operationRouteCompiled:true};
      let plan;try{plan=createFlightPlan(layout,view,stand,model);}catch{continue;}
      if(plan.supported===false||plan.routeAvailable===false)continue;
      const blockers=meta.id==='brisbane'?compileBrisbaneRequirements(layout,stand,model,plan,roundedPath,phaseCache):[];
      if(blockers===null)continue;
      const key=[meta.id,stand.plotId,aircraft.id,layout.fixedReferenceRunway?'fixed':length].join(':');
      entries[key]=[plan.runway.id,plan.stand.referenceStand??stand.plotId,blockers];accepted++;
    }
  }
    if(meta.id==='brisbane'&&Number(stand.plotId.split('-').at(-1))%10===0)console.log(`${meta.id} ${stand.plotId}: ${accepted} accepted / ${checked} checked total`);
  }
  console.log(`${meta.id}: ${accepted} accepted / ${checked} checked total`);
}
if(JSON.stringify(hashes)!==JSON.stringify(await operationsRouteSourceHashes()))throw new Error('Route inputs changed during compilation. Rerun against stable source files.');
await writeFile(new URL('../airport/operations-route-manifest.mjs',import.meta.url),`// Generated by scripts/generate-operations-routes.mjs. Do not hand edit.\n// Clearance uses the existing exact hull/wheel tests at 0.15 world units.\nexport const OPERATIONS_ROUTE_VERSION=${JSON.stringify(version)};\nexport const OPERATIONS_ROUTE_SOURCES=Object.freeze(${JSON.stringify(hashes)});\nexport const OPERATIONS_ROUTES=Object.freeze(${JSON.stringify(entries)});\n`);
console.log(`Compiled ${accepted} trusted routes; version ${version}.`);
