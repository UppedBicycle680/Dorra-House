export function clubSlug(value = '') {
  return String(value)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/\b(?:football|soccer)\s+club\b/g, ' ')
    .replace(/\bfc\b/g, ' fc ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function crestForClub(idOrName = '') {
  const slug = clubSlug(idOrName);
  return CREST_ASSETS[slug]
    || CREST_ASSETS[slug.replace(/-fc$/, '')]
    || null;
}

export function clubMonogram(name = '') {
  const words = String(name).trim().split(/\s+/).filter(Boolean);
  if (!words.length) return 'FC';
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return `${words[0][0]}${words.at(-1)[0]}`.toUpperCase();
}

